async function main() {
  const planets = Object.keys(ALL_DATA);
  console.log(`Seeding ${planets.length} planètes (${planets.join(', ')})…`);

  for (const planet of planets) {
    const data = ALL_DATA[planet];
    let count = 0;
    for (const sign of Object.keys(data)) {
      for (const house of HOUSES) {
        const interpretation = data[sign][house];
        if (!interpretation) {
          console.warn(`  ⚠️  Missing: ${planet} / ${sign} / ${house}`);
          continue;
        }
        await prisma.astroInterpretation.upsert({
          where: { planet_sign_house: { planet, sign, house } },
          update: { interpretation },
          create: { planet, sign, house, interpretation },
        });
        count++;
      }
    }
    console.log(`  ✅ ${planet}: ${count} combinaisons`);
  }
  console.log(`✅ Total: ${planets.length * 12 * 12} combinaisons dans la base.`);
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
