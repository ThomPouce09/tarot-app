export const WAIT_POOLS: Record<WaitUniverse, { fr: string[]; en: string[]; es: string[]; hi: string[] }> = {
  tarot: T,
  yijing: Y,
  runes: R,
  des: D,
};

// Mélange Fisher-Yates (copie) — comme pour les vidéos : chaque attente démarre
// sur une phrase différente, puis rotation dans l'ordre mélangé.
export function shuffledCopy<T>(arr: T[]): T[] {
  const out = arr.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

export function waitMessages(universe: WaitUniverse, lang: 'fr' | 'en' | 'es' | 'hi'): string[] {
  return shuffledCopy(WAIT_POOLS[universe][lang] ?? WAIT_POOLS[universe].fr);
}

// Routage type de tirage → univers (mêmes règles que l'API d'attente).
export function universeForType(type: string): WaitUniverse | null {
  if (type.startsWith('tarot')) return 'tarot';
  if (type.startsWith('yi-jing') || type === 'yi-qing') return 'yijing';
  if (type.startsWith('runes')) return 'runes';
  if (type.startsWith('des') || type.startsWith('astro')) return 'des';
  return null;
}
